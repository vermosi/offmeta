#!/usr/bin/env node
/**
 * Generates the canonical Scryfall oracle-tag (otag:) vocabulary from
 * src/data/scryfall-tagger-tags.txt.
 *
 * The source file lists tags grouped by letter. Art tags live under headings
 * like "A" while functional (oracle) tags live under "A (functional)".
 * Only the functional groups are valid for otag:/oracletag:/function: searches.
 *
 * Outputs two identical vocabularies so both the browser bundle and the Deno
 * edge functions can validate otag values without a network round-trip:
 *   - src/lib/scryfall/otag-vocabulary.ts
 *   - supabase/functions/_shared/otag-vocabulary.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(ROOT, 'src/data/scryfall-tagger-tags.txt');

const TARGETS = [
  resolve(ROOT, 'src/lib/scryfall/otag-vocabulary.ts'),
  resolve(ROOT, 'supabase/functions/_shared/otag-vocabulary.ts'),
];

/** @returns {string[]} sorted unique functional tag slugs */
export function parseFunctionalTags(raw) {
  const lines = raw.split(/\r?\n/);
  const tags = new Set();
  let inFunctionalSection = false;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    // Section headings are short: "A", "A (functional)", "#", "# (functional)".
    if (/\(functional\)\s*$/i.test(trimmed) && trimmed.length <= 20) {
      inFunctionalSection = true;
      continue;
    }
    if (trimmed.length <= 4 && !trimmed.includes('·')) {
      inFunctionalSection = false;
      continue;
    }
    if (!inFunctionalSection) continue;

    for (const part of trimmed.split('·')) {
      const slug = part.trim().toLowerCase();
      if (/^[a-z0-9][a-z0-9-]*$/.test(slug)) tags.add(slug);
    }
  }

  return [...tags].sort();
}

function render(tags) {
  return `// AUTO-GENERATED by scripts/generate-otag-vocabulary.mjs — do not edit by hand.
// Source: src/data/scryfall-tagger-tags.txt (Scryfall Tagger "functional" groups).
// Regenerate with: node scripts/generate-otag-vocabulary.mjs

/** Every functional (oracle) tag Scryfall currently indexes for otag: searches. */
export const SCRYFALL_ORACLE_TAGS: readonly string[] = [
${tags.map((tag) => `  '${tag}',`).join('\n')}
];

/** Lookup set for O(1) otag validation. */
export const SCRYFALL_ORACLE_TAG_SET: ReadonlySet<string> = new Set(SCRYFALL_ORACLE_TAGS);
`;
}

function main() {
  const tags = parseFunctionalTags(readFileSync(SOURCE, 'utf8'));
  if (tags.length < 100) {
    throw new Error(`Expected a large otag vocabulary, parsed only ${tags.length}`);
  }
  const output = render(tags);
  for (const target of TARGETS) writeFileSync(target, output, 'utf8');
  console.log(`Generated ${tags.length} oracle tags into ${TARGETS.length} modules.`);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  main();
}
