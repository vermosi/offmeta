#!/usr/bin/env node
/**
 * Syncs the Scryfall type catalogs into a deterministic lookup module so
 * natural-language queries can resolve subtypes ("monkey", "ape", "elder
 * dragon") into `t:` filters instead of silently dropping the word.
 *
 * Output:
 *   - supabase/functions/_shared/subtype-vocabulary.ts
 *
 * Usage:
 *   node scripts/generate-subtype-vocabulary.mjs
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = resolve(ROOT, 'supabase/functions/_shared/subtype-vocabulary.ts');

const CATALOGS = [
  ['creature', 'https://api.scryfall.com/catalog/creature-types'],
  ['planeswalker', 'https://api.scryfall.com/catalog/planeswalker-types'],
  ['land', 'https://api.scryfall.com/catalog/land-types'],
  ['artifact', 'https://api.scryfall.com/catalog/artifact-types'],
  ['enchantment', 'https://api.scryfall.com/catalog/enchantment-types'],
  ['spell', 'https://api.scryfall.com/catalog/spell-types'],
];

/**
 * Subtypes that collide with common English or MTG jargon and would hijack
 * unrelated queries if treated as a type filter.
 */
const AMBIGUOUS = new Set([
  'ape', // kept: distinctive enough, but listed here for documentation
]);
AMBIGUOUS.delete('ape');

/** Words that are also core game vocabulary — never auto-resolve to `t:`. */
const BLOCKED = new Set([
  'aura',
  'equipment',
  'saga',
  'vehicle',
  'food',
  'treasure',
  'clue',
  'blood',
  'gold',
  'map',
  'powerstone',
  'incubator',
  'role',
  'shard',
  'curse',
  'class',
  'background',
  'attraction',
  'contraption',
  'mine',
  'tower',
  'power-plant',
  'lair',
  'locus',
  'sphere',
  'desert',
  'gate',
  'cave',
  'trap',
  'arcane',
  'adventure',
  'lesson',
  'omen',
  'plains',
  'island',
  'swamp',
  'mountain',
  'forest',
  'wastes',
  'giant', // "giant" is frequently an adjective ("giant creatures")
  'wall', // often used descriptively ("wall of text")
  'egg',
  'wizard', // still resolvable via COMMON_SUBTYPES fallback ordering
]);
BLOCKED.delete('wizard');

/** @param {Record<string, string[]>} catalogs */
export function buildSubtypeVocabulary(catalogs) {
  /** @type {Map<string, { subtype: string; slug: string; categories: string[] }>} */
  const byName = new Map();

  for (const [category, values] of Object.entries(catalogs)) {
    for (const raw of values) {
      if (typeof raw !== 'string') continue;
      const subtype = raw.trim();
      if (!subtype) continue;
      const slug = subtype.toLowerCase();
      if (BLOCKED.has(slug)) continue;
      const existing = byName.get(slug);
      if (existing) {
        if (!existing.categories.includes(category)) {
          existing.categories.push(category);
        }
      } else {
        byName.set(slug, { subtype, slug, categories: [category] });
      }
    }
  }

  return [...byName.values()].sort((a, b) => a.slug.localeCompare(b.slug));
}

function renderModule(entries) {
  return `// AUTO-GENERATED by scripts/generate-subtype-vocabulary.mjs — do not edit by hand.
// Source: https://api.scryfall.com/catalog/{creature,planeswalker,land,artifact,enchantment,spell}-types
// Regenerate with: node scripts/generate-subtype-vocabulary.mjs

export interface ScryfallSubtypeEntry {
  /** Canonical subtype as printed on cards (e.g. "Monkey"). */
  subtype: string;
  /** Lowercased lookup key (e.g. "monkey"). */
  slug: string;
  /** Which type catalogs the subtype appears in. */
  categories: readonly string[];
}

export const SCRYFALL_SUBTYPES: readonly ScryfallSubtypeEntry[] = ${JSON.stringify(
    entries,
    null,
    2,
  )} as const;

/** Fast lookup of every known subtype slug. */
export const SCRYFALL_SUBTYPE_SLUGS: ReadonlySet<string> = new Set(
  SCRYFALL_SUBTYPES.map((entry) => entry.slug),
);
`;
}

async function main() {
  /** @type {Record<string, string[]>} */
  const catalogs = {};
  for (const [category, url] of CATALOGS) {
    const response = await fetch(url, {
      headers: { 'User-Agent': 'OffMetaBot/1.0', Accept: 'application/json' },
    });
    if (!response.ok) {
      throw new Error(`Failed to fetch ${url}: ${response.status}`);
    }
    const payload = await response.json();
    catalogs[category] = payload.data ?? [];
  }

  const entries = buildSubtypeVocabulary(catalogs);
  writeFileSync(TARGET, renderModule(entries), 'utf8');
  console.log(`Wrote ${entries.length} subtypes to ${TARGET}`);
}

if (process.argv[1] && process.argv[1].endsWith('generate-subtype-vocabulary.mjs')) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
