#!/usr/bin/env node
/**
 * Syncs the Scryfall set list into a deterministic lookup module so natural
 * language queries can resolve set names ("the hobbit", "bloomburrow") to
 * Scryfall set codes — including sets that are announced but not yet released.
 *
 * Output:
 *   - supabase/functions/_shared/set-vocabulary.ts
 *
 * Usage:
 *   node scripts/generate-set-vocabulary.mjs
 *   node scripts/generate-set-vocabulary.mjs --json=sets.json   # parse a local copy
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SETS_URL = 'https://api.scryfall.com/sets';
const TARGET = resolve(ROOT, 'supabase/functions/_shared/set-vocabulary.ts');

/** Set types that are never useful as a natural-language search target. */
const EXCLUDED_SET_TYPES = new Set([
  'token',
  'memorabilia',
  'minigame',
  'vanguard',
  'treasure_chest',
  'alchemy',
]);

/** @param {{ data: any[] }} payload */
export function buildSetVocabulary(payload) {
  return payload.data
    .filter((set) => !set.digital && !EXCLUDED_SET_TYPES.has(set.set_type))
    .filter((set) => typeof set.name === 'string' && typeof set.code === 'string')
    .map((set) => ({
      code: set.code.toLowerCase(),
      name: set.name,
      setType: set.set_type,
      releasedAt: set.released_at ?? null,
      parentSetCode: set.parent_set_code ? set.parent_set_code.toLowerCase() : null,
    }))
    .sort((a, b) => a.code.localeCompare(b.code));
}

function renderModule(sets) {
  return `// AUTO-GENERATED by scripts/generate-set-vocabulary.mjs — do not edit by hand.
// Source: ${SETS_URL}
// Regenerate with: node scripts/generate-set-vocabulary.mjs

export interface ScryfallSetEntry {
  /** Scryfall set code, lowercase (e.g. "hob"). */
  code: string;
  /** Official set name (e.g. "The Hobbit"). */
  name: string;
  /** Scryfall set_type (expansion, commander, eternal, ...). */
  setType: string;
  /** ISO release date; may be in the future for announced sets. */
  releasedAt: string | null;
  /** Parent set code for supplemental products (commander decks, etc). */
  parentSetCode: string | null;
}

export const SCRYFALL_SETS: readonly ScryfallSetEntry[] = ${JSON.stringify(sets, null, 2)};

export const SCRYFALL_SET_CODES: ReadonlySet<string> = new Set(
  SCRYFALL_SETS.map((set) => set.code),
);
`;
}

async function main() {
  const localArg = process.argv.find((arg) => arg.startsWith('--json='));
  const payload = localArg
    ? JSON.parse(readFileSync(resolve(ROOT, localArg.slice('--json='.length)), 'utf8'))
    : await (async () => {
        const response = await fetch(SETS_URL, {
          headers: { 'User-Agent': 'offmeta-set-sync', Accept: 'application/json' },
        });
        if (!response.ok) throw new Error(`Failed to fetch ${SETS_URL}: ${response.status}`);
        return response.json();
      })();

  const sets = buildSetVocabulary(payload);
  if (sets.length < 500) {
    throw new Error(`Parsed suspiciously few sets (${sets.length}). Aborting.`);
  }

  writeFileSync(TARGET, renderModule(sets), 'utf8');
  console.log(`Synced ${sets.length} Scryfall sets.`);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  await main();
}
