#!/usr/bin/env node
/**
 * Syncs the full Scryfall Tagger vocabulary (both art and functional tags)
 * from https://scryfall.com/docs/tagger-tags.
 *
 * Scryfall's tag list grows continuously, so a hand-pasted snapshot goes stale
 * quickly: hallucinated-looking tags get stripped from queries even though they
 * are real, and genuinely new tags are unusable. This script refetches the
 * canonical list and regenerates every derived module.
 *
 * Outputs:
 *   - src/data/scryfall-tagger-tags.txt              (human-readable snapshot)
 *   - src/lib/scryfall/otag-vocabulary.ts            (browser, functional tags)
 *   - supabase/functions/_shared/otag-vocabulary.ts  (Deno, functional tags)
 *   - supabase/functions/_shared/art-tag-vocabulary.ts (Deno, art tags)
 *
 * Usage:
 *   node scripts/generate-tagger-vocabulary.mjs              # fetch live
 *   node scripts/generate-tagger-vocabulary.mjs --html=f.html # parse a local copy
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS_URL = 'https://scryfall.com/docs/tagger-tags';

const SNAPSHOT = resolve(ROOT, 'src/data/scryfall-tagger-tags.txt');
const ORACLE_TARGETS = [
  resolve(ROOT, 'src/lib/scryfall/otag-vocabulary.ts'),
  resolve(ROOT, 'supabase/functions/_shared/otag-vocabulary.ts'),
];
const ART_TARGET = resolve(ROOT, 'supabase/functions/_shared/art-tag-vocabulary.ts');

/**
 * Scryfall links every tag as `/search?q=art%3A<slug>` (art tags) or
 * `/search?q=oracletag%3A<slug>` (functional tags), which is far more stable
 * than the surrounding letter-heading markup.
 *
 * @param {string} html
 * @returns {{ art: string[]; oracle: string[] }}
 */
export function parseTaggerTags(html) {
  const collect = (prefix) => {
    const pattern = new RegExp(`q=${prefix}%3A([^"&]+)`, 'gi');
    const tags = new Set();
    let match;
    while ((match = pattern.exec(html)) !== null) {
      const slug = decodeURIComponent(match[1]).trim().toLowerCase();
      if (slug) tags.add(slug);
    }
    return [...tags].sort();
  };

  return { art: collect('art'), oracle: collect('oracletag') };
}

/** Groups tags by leading character for the readable snapshot. */
function groupByLetter(tags) {
  const groups = new Map();
  for (const tag of tags) {
    const first = tag[0];
    const key = /[a-z]/.test(first) ? first.toUpperCase() : '#';
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(tag);
  }
  return groups;
}

function renderSnapshot({ art, oracle }) {
  const artGroups = groupByLetter(art);
  const oracleGroups = groupByLetter(oracle);
  const letters = [...new Set([...artGroups.keys(), ...oracleGroups.keys()])].sort((a, b) =>
    a === '#' ? -1 : b === '#' ? 1 : a.localeCompare(b),
  );

  const lines = [
    'Tagger Tags',
    '',
    `Synced from ${DOCS_URL} — regenerate with:`,
    'node scripts/generate-tagger-vocabulary.mjs',
    '',
    'Art tags (art:, atag:, arttag:) describe what is depicted in the illustration.',
    'Functional tags (otag:, oracletag:, function:) describe what the card does.',
    '',
    `Art tags: ${art.length} · Functional tags: ${oracle.length}`,
    '',
  ];

  for (const letter of letters) {
    if (artGroups.has(letter)) {
      lines.push(letter, artGroups.get(letter).join(' · '), '');
    }
    if (oracleGroups.has(letter)) {
      lines.push(`${letter} (functional)`, oracleGroups.get(letter).join(' · '), '');
    }
  }

  return `${lines.join('\n')}\n`;
}

function renderModule({ constName, setName, doc, tags }) {
  return `// AUTO-GENERATED by scripts/generate-tagger-vocabulary.mjs — do not edit by hand.
// Source: ${DOCS_URL}
// Regenerate with: node scripts/generate-tagger-vocabulary.mjs

${doc}
export const ${constName}: readonly string[] = [
${tags.map((tag) => `  ${JSON.stringify(tag)},`).join('\n')}
];

/** Lookup set for O(1) validation. */
export const ${setName}: ReadonlySet<string> = new Set(${constName});
`;
}

async function loadHtml() {
  const localArg = process.argv.find((arg) => arg.startsWith('--html='));
  if (localArg) return readFileSync(resolve(ROOT, localArg.slice('--html='.length)), 'utf8');

  const response = await fetch(DOCS_URL, {
    headers: { 'User-Agent': 'offmeta-tagger-sync', Accept: 'text/html' },
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${DOCS_URL}: ${response.status}`);
  }
  return response.text();
}

async function main() {
  const html = await loadHtml();
  const { art, oracle } = parseTaggerTags(html);

  // Guard against a markup change silently emptying the vocabulary.
  if (oracle.length < 4000 || art.length < 8000) {
    throw new Error(
      `Parsed suspiciously few tags (art=${art.length}, functional=${oracle.length}). Aborting.`,
    );
  }

  writeFileSync(SNAPSHOT, renderSnapshot({ art, oracle }), 'utf8');

  const oracleModule = renderModule({
    constName: 'SCRYFALL_ORACLE_TAGS',
    setName: 'SCRYFALL_ORACLE_TAG_SET',
    doc: '/** Every functional (oracle) tag Scryfall indexes for otag:/oracletag:/function: searches. */',
    tags: oracle,
  });
  for (const target of ORACLE_TARGETS) writeFileSync(target, oracleModule, 'utf8');

  writeFileSync(
    ART_TARGET,
    renderModule({
      constName: 'SCRYFALL_ART_TAGS',
      setName: 'SCRYFALL_ART_TAG_SET',
      doc: '/** Every art tag Scryfall indexes for art:/atag:/arttag: searches. */',
      tags: art,
    }),
    'utf8',
  );

  console.log(
    `Synced ${oracle.length} functional tags and ${art.length} art tags from Scryfall Tagger.`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  await main();
}
